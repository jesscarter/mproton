#!/usr/bin/env python3
"""Regenerate bench/mpbench_shaders.h from bench/mpbench.hlsl.

The header holds:
  - the HLSL source text (D3D11, and D3D12 with --d3d12-shaders dxbc, compile it at runtime),
  - DXIL (SM 6.0) blobs for D3D12, signed by dxc's libdxil,
  - SPIR-V 1.0 blobs for the raw Vulkan scenes.

Only needed when the shaders change; building mpbench itself does not need dxc.
Usage: DXC=/path/to/dxc bench/gen_shaders.py   (default: dxc on PATH)
dxc releases: https://github.com/microsoft/DirectXShaderCompiler/releases (linux_dxc_*.tar.gz or the macOS build)
"""
import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "mpbench.hlsl")
OUT = os.path.join(HERE, "mpbench_shaders.h")
DXC = os.environ.get("DXC", "dxc")

DXIL = [("vs_quad", "vs"), ("ps_flat", "ps"), ("vs_full", "vs"), ("ps_heavy", "ps"),
        ("vs_point", "vs"), ("gs_quad", "gs"), ("ps_col", "ps"), ("vs_so", "vs"),
        ("vs_patch", "vs"), ("hs_main", "hs"), ("ds_disk", "ds")]
SPIRV = [("vs_quad", "vs"), ("ps_flat", "ps"), ("vs_full", "vs"), ("ps_heavy", "ps")]


def dxc(entry, stage, extra):
    with tempfile.TemporaryDirectory() as td:
        out = os.path.join(td, "o.bin")
        if stage not in ("vs", "ds", "gs"):
            extra = [e for e in extra if e != "-fvk-invert-y"]
        cmd = [DXC, "-nologo", "-E", entry, "-T", f"{stage}_6_0", "-O3", "-Fo", out] + extra + [SRC]
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode:
            sys.exit(f"dxc failed for {entry}:\n{r.stderr}")
        with open(out, "rb") as f:
            return f.read()


def c_array(name, data):
    lines = [f"alignas(4) static const unsigned char {name}[{len(data)}] = {{"]
    for i in range(0, len(data), 24):
        lines.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    src = open(SRC).read()
    if ")MPHLSL\"" in src:
        sys.exit("HLSL source contains the raw-string delimiter")
    parts = ["// GENERATED by bench/gen_shaders.py from bench/mpbench.hlsl. Do not edit.",
             f"// dxc: {subprocess.run([DXC, '--version'], capture_output=True, text=True).stdout.strip()}",
             "#pragma once", "#include <cstddef>",
             "struct MpBlob { const char *name; const unsigned char *data; size_t size; };",
             f'static const char k_hlsl[] = R"MPHLSL({src})MPHLSL";']
    for kind, items, extra in (("dxil", DXIL, ["-D", "MP_FEAT_GS", "-D", "MP_FEAT_SO", "-D", "MP_FEAT_TESS",
                                                 "-Qstrip_debug", "-Qstrip_reflect"]),
                               ("spirv", SPIRV, ["-spirv", "-D", "MP_VK", "-fvk-invert-y",
                                                 "-fspv-target-env=vulkan1.0"])):
        table = []
        for entry, stage in items:
            blob = dxc(entry, stage, extra)
            parts.append(c_array(f"k_{kind}_{entry}", blob))
            table.append(f'    {{"{entry}", k_{kind}_{entry}, sizeof k_{kind}_{entry}}},')
        parts.append(f"static const MpBlob k_{kind}[] = {{\n" + "\n".join(table) + "\n    {nullptr, nullptr, 0},\n};")
    with open(OUT, "w") as f:
        f.write("\n\n".join(parts) + "\n")
    print(f"wrote {OUT} ({os.path.getsize(OUT)} bytes)")


if __name__ == "__main__":
    main()
