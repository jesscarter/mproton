#!/bin/bash
# Build "mproton Library.app" (a tiny wrapper that runs library/mproton-library) so the library
# can be started from Finder, Spotlight or the Dock. Usage: library/make-app.sh [dest dir]
# Default destination: ~/Applications. Nothing is signed or installed system-wide.
set -euo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
dest="${1:-$HOME/Applications}"
app="$dest/mproton Library.app"
mkdir -p "$app/Contents/MacOS"
cat > "$app/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>CFBundleName</key><string>mproton Library</string>
  <key>CFBundleIdentifier</key><string>dev.mproton.library</string>
  <key>CFBundleExecutable</key><string>mproton-library</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>1</string>
  <key>LSUIElement</key><true/>
</dict></plist>
PLIST
cat > "$app/Contents/MacOS/mproton-library" <<SH
#!/bin/bash
# Generated by $here/make-app.sh. Runs the library server from the checkout; its log goes to
# ~/Library/Logs/mproton-library.log. Quit it with: pkill -f mproton_library.py
mkdir -p "\$HOME/Library/Logs"
exec "$here/mproton-library" >>"\$HOME/Library/Logs/mproton-library.log" 2>&1
SH
chmod +x "$app/Contents/MacOS/mproton-library"
echo "built: $app"
