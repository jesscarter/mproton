#!/usr/bin/env python3
"""Build the mproton Wine patch series: Proton's Wine commits replayed onto athei's arm64-patched.

usage: build-series.py <wine-repo> <athei-ref> <proton-ref> <upstream-base> <upstream-top> <triage-tsv> <out-tsv>

<wine-repo> must have all four refs.  The script creates/resets branch `mproton/series` at
<athei-ref> in a worktree next to the repo and cherry-picks Proton's commits
(<upstream-base>..<proton-ref>) onto it.

Each Proton commit gets one status:
  dropped-upstream   already in <upstream-base>..<upstream-top> (patch-id, `cherry picked from`,
                     same author+subject, or the pick came out empty)
  dropped-reverted   Proton reverts it later in its own history (both commits dropped)
  skipped-linux      Linux-only group from docs/wine-patch-triage.md
  skipped-generated  only deletes or regenerates generated files (configure, thunks, syscalls)
  applied            cherry-picked cleanly (pass N)
  hand-merged        conflicted; resolved by hand on the branch (trailer `mproton-resolved:`)
  conflict           does not apply on the 11.20 base; not carried (see docs/wine-tree.md)

Order: the portable groups first (game fixes; PE side; winevulkan/dxgi/steam), then the
likely-conflict groups, then retry passes over the conflicts in Proton's order until a
pass makes no progress.
"""
import os, re, subprocess, sys, collections

repo, athei, proton, ubase, utop, triage, out = sys.argv[1:8]

def git(*a, cwd=None, check=True, inp=None):
    r = subprocess.run(["git", *a], cwd=cwd or repo, capture_output=True, text=True, input=inp, errors="replace")
    if check and r.returncode:
        raise SystemExit(f"git {' '.join(a)} failed:\n{r.stdout}\n{r.stderr}")
    return r

# Pass order, by triage group (wine-patches/triage/proton-commits.tsv).
PASSES = [
    ("game fixes", ["other PE-side game / app fixes",
                    "anti-cheat / launchers (EAC, BattlEye, EA, Ubisoft, CEF)"]),
    ("PE side", ["d3dx / d3dcompiler / ddraw / dxgi PE side",
                 "GPU vendor libs (amd_ags, atiadlxx, amdxc, nvapi, dxgi vendor)",
                 "multimedia (winegstreamer, mf*, media-converter, quartz, wm*)",
                 "networking (ws2_32, nsiproxy, iphlpapi, winhttp, wininet)",
                 "prefix / registry defaults (wine.inf, wineboot, fonts)",
                 "speech / TTS (windows.media.speech, protontts, Vosk, Piper)",
                 "winebus / HID / Steam Input / controllers",
                 "audio drivers (winepulse/winealsa) & mmdevapi"]),
    ("winevulkan / steam", ["winevulkan / win32u Vulkan / OpenXR / vrclient",
                            "Proton integration (steam.exe, proton hooks, lsteamclient, env vars)"]),
    ("core (likely conflict)", ["ARM64 / ARM64EC / FEX / WoW64",
                                "ntdll unix side (virtual memory, signals, sync, process)",
                                "wineserver core",
                                "win32u (windows, messages, display, d3dkmt)",
                                "OpenGL (opengl32 / win32u opengl / wined3d)",
                                "fullscreen hack (fshack, win32u/opengl32 side)",
                                "loader / preloader / build system (configure, makedep, winebuild, winegcc)"]),
]
LINUX_GROUPS = {
    "winex11.drv (window mgmt, input, XInput2, Vulkan surfaces)",
    "winewayland.drv",
    "gamescope / Steam Deck",
    "fsync / ntsync / in-process sync",
    "Linux tracing / debug (ftrace, gpuvis, uffd, memfd)",
}
# Proton commits that only delete generated files; the series regenerates them instead.
GENERATED = {
    "c880d1ca039": "configure: Remove configure and config.h.in.",
    "6a69d9a5c01": "winevulkan: Remove autogenerated files.",
    "55d20e52afe": "ntdll, win32u: Remove generated syscall files.",
}

tri = {}
for line in open(triage):
    f = line.rstrip("\n").split("\t")
    if f[0] == "commit": continue
    tri[f[0]] = (f[1], f[2])

def pids(rng, reverse=False):
    args = ["log", "-p", "--no-merges"] + (["--reverse"] if reverse else []) + [rng]
    log = subprocess.run(["git", *args], cwd=repo, capture_output=True, check=True).stdout
    r = subprocess.run(["git", "patch-id", "--stable"], input=log, capture_output=True, cwd=repo)
    m = {}
    for l in r.stdout.decode().splitlines():
        p, c = l.split()
        m[c] = p
    return m

print("computing patch-ids...", file=sys.stderr)
up_pid = set(pids(f"{ubase}..{utop}").values())
up_commits = set(git("rev-list", f"{ubase}..{utop}").stdout.split())
up_subj = {}
for l in git("log", "--format=%H%x09%an%x09%s", f"{ubase}..{utop}").stdout.splitlines():
    h, an, s = l.split("\t", 2)
    up_subj.setdefault((an, s), h)
pr_pid = pids(f"{ubase}..{proton}", reverse=True)

commits = []
for l in git("log", "--reverse", "--no-merges", "--format=%H%x09%an%x09%s", f"{ubase}..{proton}").stdout.splitlines():
    h, an, s = l.split("\t", 2)
    body = git("log", "-1", "--format=%b", h).stdout
    commits.append(dict(h=h, an=an, s=s, body=body))

# Reverts inside Proton's own history: drop both the commit and its revert.
by_sha = {c["h"]: c for c in commits}
reverted = {}
for c in commits:
    m = re.search(r"This reverts commit ([0-9a-f]{7,40})", c["body"])
    if m:
        for o in commits:
            if o["h"].startswith(m.group(1)) and o is not c:
                reverted[o["h"]] = c["h"]; reverted[c["h"]] = o["h"]

status = collections.OrderedDict()
for c in commits:
    h = c["h"]; short = h[:11]
    grp, cat = tri.get(short, ("other PE-side game / app fixes", "portable"))
    c["grp"] = grp
    note = ""
    cp = re.findall(r"cherry picked from commit ([0-9a-f]{40})", c["body"])
    if pr_pid.get(h) in up_pid:
        st, note = "dropped-upstream", "same patch-id upstream"
    elif any(x in up_commits for x in cp):
        st, note = "dropped-upstream", "cherry-picked from " + next(x for x in cp if x in up_commits)[:11]
    elif (c["an"], c["s"]) in up_subj and "HACK" not in c["s"]:
        st, note = "dropped-upstream", "same author+subject upstream: " + up_subj[(c["an"], c["s"])][:11]
    elif h in reverted:
        st, note = "dropped-reverted", "reverted in Proton by/with " + reverted[h][:11]
    elif short in GENERATED:
        st, note = "skipped-generated", "generated files are regenerated in the last patch"
    elif grp in LINUX_GROUPS or cat == "linux":
        st, note = "skipped-linux", grp
    else:
        st = "pending"
    status[h] = [st, note, 0]

wt = os.path.abspath(os.path.join(repo, "..", "series"))
RESUME = os.environ.get("RESUME") == "1"
if RESUME:
    # Continue on the existing branch (after hand merges): keep the recorded statuses and
    # only run retry passes over the commits that still conflict.
    for line in open(out):
        f = line.rstrip("\n").split("\t")
        if f[0] == "order": continue
        for h in status:
            if h.startswith(f[1]):
                status[h] = [f[2], f[7], int(f[3] or 0)]
else:
    if not os.path.isdir(wt):
        git("worktree", "add", "-f", wt, athei)
    git("checkout", "-q", "-B", "mproton/series", athei, cwd=wt)
# RESUME=1 continues on the existing branch; NOPASS=1 (with RESUME=1) only rewrites the TSV.
env = dict(os.environ, GIT_COMMITTER_NAME="mproton", GIT_COMMITTER_EMAIL="mproton@localhost")

def pick(h):
    r = subprocess.run(["git", "cherry-pick", "-x", "--allow-empty", h], cwd=wt, capture_output=True, text=True, env=env, errors="replace")
    if r.returncode == 0:
        # empty result => already there
        if git("diff", "--quiet", "HEAD~1", "HEAD", cwd=wt, check=False).returncode == 0:
            git("reset", "-q", "--hard", "HEAD~1", cwd=wt)
            return "empty", ""
        return "ok", ""
    files = git("diff", "--name-only", "--diff-filter=U", cwd=wt, check=False).stdout.split()
    if not files and ("empty" in r.stderr or "nothing to commit" in r.stdout + r.stderr):
        subprocess.run(["git", "cherry-pick", "--skip"], cwd=wt, capture_output=True)
        return "empty", ""
    subprocess.run(["git", "cherry-pick", "--abort"], cwd=wt, capture_output=True)
    git("reset", "-q", "--hard", "HEAD", cwd=wt)
    return "conflict", " ".join(files) or r.stderr.strip().splitlines()[-1]

def run(cands, passno, label):
    n = 0
    for c in cands:
        st = status[c["h"]]
        if st[0] not in ("pending", "conflict"): continue
        if c["h"] in onbranch: continue
        res, info = pick(c["h"])
        if res == "ok":
            st[:] = ["applied", label, passno]; n += 1
        elif res == "empty":
            st[:] = ["dropped-upstream", "pick came out empty on 11.20", passno]
        else:
            st[:] = ["conflict", info, passno]
    print(f"pass {passno} ({label}): {n} applied", file=sys.stderr)
    return n

# Commits already on the branch (e.g. hand-merged ones) count as applied.
onbranch = {}
for blk in git("log", "--format=%H %b%x00", f"{athei}..mproton/series", cwd=wt).stdout.split("\x00"):
    m = re.findall(r"cherry picked from commit ([0-9a-f]{40})", blk)
    if m:
        r = re.search(r"mproton-resolved: (.*)", blk)
        onbranch[m[-1]] = r.group(1).strip() if r else None
for h, hand in onbranch.items():
    if h in status:
        status[h][:] = ["hand-merged" if hand else "applied", hand or ("" if status[h][0] == "hand-merged" else status[h][1]), status[h][2]]
for h, st in status.items():
    if st[0] in ("applied", "hand-merged") and h not in onbranch:   # dropped from the branch by hand
        st[:] = ["conflict", "removed from the series", st[2]]

# Manual statuses (wine/scripts/manual-status.tsv) for conflicting commits that need no port.
manual = os.path.join(os.path.dirname(os.path.abspath(__file__)), "manual-status.tsv")
if os.path.exists(manual):
    for line in open(manual):
        if line.startswith("#") or not line.strip(): continue
        mc, mst, mnote = line.rstrip("\n").split("\t", 2)
        for h in status:
            if h.startswith(mc) and h not in onbranch:
                # a manual status is final: run() only picks pending/conflict, so mark it held
                status[h][:] = [mst if mst != "conflict" else "held-conflict", mnote, status[h][2]]

passno = max([v[2] for v in status.values()] + [0])
if not RESUME:
    for label, groups in PASSES:
        passno += 1
        run([c for c in commits if c["grp"] in groups], passno, label)
while os.environ.get("NOPASS") != "1":   # NOPASS=1: only rewrite <out-tsv> from the branch
    passno += 1
    if not run(commits, passno, "retry"):
        break

with open(out, "w") as f:
    f.write("order\tcommit\tstatus\tpass\tgroup\tauthor\tsubject\tnote\n")
    order = {}
    applied = git("log", "--reverse", "--format=%H %b%x00", f"{athei}..mproton/series", cwd=wt).stdout.split("\x00")
    for i, blk in enumerate(applied, 1):
        m = re.findall(r"cherry picked from commit ([0-9a-f]{40})", blk)
        if m: order[m[-1]] = i
    for c in commits:
        st, note, p = status[c["h"]]
        if st == "held-conflict": st = "conflict"
        f.write(f"{order.get(c['h'], '')}\t{c['h'][:11]}\t{st}\t{p or ''}\t{c['grp']}\t{c['an']}\t{c['s']}\t{note}\n")
cnt = collections.Counter(v[0] for v in status.values())
print(dict(cnt), file=sys.stderr)
